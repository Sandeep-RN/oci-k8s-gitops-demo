#!/usr/bin/env bash
# One-time bootstrap (ADR 0003): project compartment + versioned Terraform
# state bucket, created outside Terraform to avoid the chicken-and-egg problem.
#
# Idempotent: safe to re-run. Existing resources are reused, never replaced.
# Writes two git-ignored files consumed by Terraform:
#   terraform/backend.hcl          bucket, namespace, region, auth profile
#   terraform/oke/terraform.tfvars tenancy/compartment OCIDs (only if absent)
# OCIDs are never printed, because terminal output ends up in screenshots.
#
# Usage: scripts/bootstrap-state.sh
# Env:   OCI_CLI (default: oci), OCI_PROFILE (default: oke-demo),
#        OCI_AUTH (default: security_token), OCI_CONFIG_FILE (default: ~/.oci/config),
#        OCI_REGION (default: ap-hyderabad-1)
set -euo pipefail

OCI_CLI="${OCI_CLI:-oci}"
PROFILE="${OCI_PROFILE:-oke-demo}"
AUTH="${OCI_AUTH:-security_token}"
CONFIG_FILE="${OCI_CONFIG_FILE:-$HOME/.oci/config}"
REGION="${OCI_REGION:-ap-hyderabad-1}"

COMPARTMENT_NAME="oci-k8s-gitops-demo"
BUCKET_NAME="oci-k8s-gitops-demo-tfstate"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_FILE="$REPO_ROOT/terraform/backend.hcl"
OKE_TFVARS="$REPO_ROOT/terraform/oke/terraform.tfvars"

oci_cmd() {
  "$OCI_CLI" --config-file "$CONFIG_FILE" --profile "$PROFILE" --auth "$AUTH" \
    --region "$REGION" "$@"
}

log() { printf '==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

command -v "$OCI_CLI" >/dev/null 2>&1 || [ -x "$OCI_CLI" ] || die "OCI CLI not found: $OCI_CLI"
[ -f "$CONFIG_FILE" ] || die "OCI config not found: $CONFIG_FILE"

# Tenancy OCID from the profile, read without echoing it.
TENANCY="$(awk -F= -v p="[$PROFILE]" '
  $0 == p { f = 1; next }
  /^\[/   { f = 0 }
  f && $1 ~ /^[ \t]*tenancy[ \t]*$/ { gsub(/[ \t\r]/, "", $2); print $2 }
' "$CONFIG_FILE")"
[ -n "$TENANCY" ] || die "no tenancy in profile [$PROFILE] of $CONFIG_FILE"

# Fail fast with a clear message if the session token has expired.
oci_cmd iam region list --query 'data[0].name' --raw-output >/dev/null 2>&1 \
  || die "OCI auth failed. Run: oci session authenticate --region $REGION --profile-name $PROFILE"

# --- Compartment -------------------------------------------------------------
COMPARTMENT_ID="$(oci_cmd iam compartment list -c "$TENANCY" --all \
  --lifecycle-state ACTIVE --name "$COMPARTMENT_NAME" \
  --query 'data[0].id' --raw-output 2>/dev/null || true)"

if [ -z "$COMPARTMENT_ID" ] || [ "$COMPARTMENT_ID" = "null" ]; then
  log "creating compartment $COMPARTMENT_NAME (waits until ACTIVE)"
  COMPARTMENT_ID="$(oci_cmd iam compartment create -c "$TENANCY" \
    --name "$COMPARTMENT_NAME" \
    --description "OCI k8s GitOps demo: k3s node, OKE target, state bucket" \
    --wait-for-state ACTIVE --query 'data.id' --raw-output)"
else
  log "compartment $COMPARTMENT_NAME exists"
fi

# --- State bucket ------------------------------------------------------------
NAMESPACE="$(oci_cmd os ns get --query 'data' --raw-output)"

if oci_cmd os bucket get --namespace-name "$NAMESPACE" --bucket-name "$BUCKET_NAME" \
     >/dev/null 2>&1; then
  log "bucket $BUCKET_NAME exists; ensuring versioning is enabled and access is private"
  oci_cmd os bucket update --namespace-name "$NAMESPACE" --bucket-name "$BUCKET_NAME" \
    --versioning Enabled --public-access-type NoPublicAccess >/dev/null
else
  # New IAM compartments can take a minute to propagate to Object Storage.
  for attempt in 1 2 3 4 5 6; do
    if oci_cmd os bucket create --namespace-name "$NAMESPACE" -c "$COMPARTMENT_ID" \
         --name "$BUCKET_NAME" --versioning Enabled \
         --public-access-type NoPublicAccess >/dev/null 2>&1; then
      log "created bucket $BUCKET_NAME (versioned, private)"
      break
    fi
    [ "$attempt" -eq 6 ] && die "bucket create failed after retries"
    log "bucket create not yet possible (compartment propagating?); retry $attempt/5 in 20s"
    sleep 20
  done
fi

# --- Git-ignored config files ------------------------------------------------
# backend.hcl holds no secret, but the namespace identifies the tenancy, and the
# repo is public, so it stays out of git (see .gitignore).
cat > "$BACKEND_FILE" <<EOF
# Generated by scripts/bootstrap-state.sh. Git-ignored. Do not commit.
bucket              = "$BUCKET_NAME"
namespace           = "$NAMESPACE"
region              = "$REGION"
auth                = "SecurityToken"
config_file_profile = "$PROFILE"
EOF
log "wrote terraform/backend.hcl"

if [ -f "$OKE_TFVARS" ]; then
  log "terraform/oke/terraform.tfvars exists; left unchanged"
else
  mkdir -p "$(dirname "$OKE_TFVARS")"
  cat > "$OKE_TFVARS" <<EOF
# Generated by scripts/bootstrap-state.sh. Git-ignored. Do not commit.
tenancy_ocid     = "$TENANCY"
compartment_ocid = "$COMPARTMENT_ID"
region           = "$REGION"
oci_profile      = "$PROFILE"
EOF
  log "wrote terraform/oke/terraform.tfvars (add bastion_client_cidr before applying)"
fi

log "done"
